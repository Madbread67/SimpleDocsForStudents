def get_all_variable_names() -> list:
    """Возвращает список всех имен переменных"""
    all_vars = []
    for category in TEMPLATE_VARIABLES.values():
        all_vars.extend(category.keys())
    return sorted(all_vars)

def get_variables_by_category() -> dict:
    """Возвращает переменные сгруппированные по категориям"""
    return TEMPLATE_VARIABLES

def get_variable_description(variable_name: str) -> str:
    """Возвращает описание переменной по ее имени"""
    for category in TEMPLATE_VARIABLES.values():
        if variable_name in category:
            return category[variable_name]
    return f"Переменная '{variable_name}' не найдена"
